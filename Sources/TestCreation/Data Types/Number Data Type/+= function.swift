extension Number {
    
    
    
    
    
    public static func += (lhs: inout Number, rhs: Number) {
        
        lhs = lhs + rhs
        
    }
    
    public static func -= (lhs: inout Number, rhs: Number) {
        
        lhs = lhs - rhs
        
    }
}
